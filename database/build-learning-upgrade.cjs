const fs=require('node:fs'),path=require('node:path');
const dir=path.join(__dirname,'migrations');
const names=fs.readdirSync(dir).filter(n=>/^20260910_(11|12|13|14|15)_.*\.sql$/.test(n)).sort();
if(names.length!==5)throw Error('Expected exactly five learning migrations');
const preflight=`-- Generated by database/build-learning-upgrade.cjs. Apply ONCE after 20260909_10.
-- All five migrations are one transaction. No accounting history is deleted or repriced.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='120s';
DO $$ BEGIN
 IF to_regclass('csat_internal.schema_migrations') IS NULL THEN RAISE EXCEPTION 'Missing accounting upgrade.'; END IF;
 IF NOT EXISTS(SELECT 1 FROM csat_internal.schema_migrations WHERE version='20260909_10') THEN RAISE EXCEPTION 'Apply accounting migration 10 first.'; END IF;
 IF EXISTS(SELECT 1 FROM csat_internal.schema_migrations WHERE version LIKE '20260910_%') THEN RAISE EXCEPTION 'Learning migration already present. Check versions; do not replay this bundle.'; END IF;
END $$;
`;
const sections=names.map(name=>'\n-- '+name+'\n'+fs.readFileSync(path.join(dir,name),'utf8').replace(/^BEGIN;\s*$/gm,'').replace(/^COMMIT;\s*$/gm,'').replace(/^NOTIFY pgrst,.*$/gm,''));
fs.writeFileSync(path.join(__dirname,'upgrade-learning-portal.sql'),preflight+sections.join('\n')+"\nNOTIFY pgrst,'reload schema';\nCOMMIT;\n");
console.log('Generated upgrade-learning-portal.sql from '+names.join(', '));
